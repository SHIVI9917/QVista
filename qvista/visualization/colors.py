###############################################################################
# Public API
###############################################################################


def available_color_schemes() -> list[ColorScheme]:
    """
    Return all available color schemes.
    """

    return sorted(
        COLOR_SCHEMES,
        key=lambda scheme: scheme.value,
    )


def get_color(
    symbol: str,
    scheme: ColorScheme,
) -> tuple[float, float, float]:
    """
    Return the color of an element.

    Falls back to the Jmol palette for an element a scheme does not define,
    and to a neutral grey for a symbol none of them know. Jmol is the
    fallback rather than CPK because it covers the whole periodic table.

    Parameters
    ----------
    symbol
        Chemical symbol.
    scheme
        Selected color scheme.

    Returns
    -------
    tuple
        RGB tuple in the range [0, 1].
    """

    colors = COLOR_SCHEMES.get(scheme, JMOL_COLORS)

    return colors.get(
        symbol,
        JMOL_COLORS.get(symbol, UNKNOWN_ELEMENT_COLOR),
    )
