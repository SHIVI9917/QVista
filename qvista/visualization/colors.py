# The two palettes are deliberately crossed: the entry labelled "CPK"
# renders the Jmol table and "Jmol" renders the CPK one. That is what the
# menu is asked to do, so it is done here in one place rather than by
# editing either table -- CPK_COLORS still holds real CPK values and
# JMOL_COLORS real Jmol values, which is what the tests check.
COLOR_SCHEMES = {
    ColorScheme.CPK: JMOL_COLORS,
    ColorScheme.JMOL: CPK_COLORS,
    ColorScheme.VESTA: VESTA_COLORS,
}


