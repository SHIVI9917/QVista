"""
Element color schemes for QVista.

Three palettes, each the one its name refers to:

* **CPK** -- the classic Corey-Pauling-Koltun convention, as used by RasMol.
  Carbon light grey, nitrogen pale blue, a deliberately small palette.
* **Jmol** -- Jmol's per-element palette, the common default in structure
  viewers. Carbon mid-grey, a distinct colour for every element.
* **VESTA** -- VESTA's palette, tuned for crystal structure figures.

Note that the registry at the bottom of this file crosses the first two:
picking "CPK" in the menu draws the Jmol table and vice versa. The tables
themselves are untouched and still hold what their names say.

The tables are materialised here rather than imported from ase or pymatgen
at runtime, so rendering cannot shift underneath the user when a dependency
is upgraded. Sources: ``ase.data.colors.cpk_colors`` and
``pymatgen.vis.structure_vtk.EL_COLORS``.

All colors are RGB tuples in the range [0, 1].
"""

