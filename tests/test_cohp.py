"""
Tests for the bonding analysis tools.

LOBSTER output is plain text, so the fixtures are written out in the real
format -- including a ``COHPCAR.lobster`` laid out the way LOBSTER lays
one out, since the whole point of reading it through pymatgen is that the
column layout is not obvious and a fixture that cheats would test
nothing.

That layout, from the file itself: line 2 holds the number of entries
(the cell average plus one per interaction), the number of spin channels
and the number of energies; then one label per entry; then one row per
energy holding ``1 + 2 * entries * spins`` numbers -- the energy, then a
(value, integral) pair per entry for the first spin, then the same again
for the second.
"""

from __future__ import annotations

import numpy as np
import pytest

from qvista.services import cohp as ch


# ------------------------------------------------------------
# Fixtures
# ------------------------------------------------------------


def icohplist(spin_polarized: bool = True) -> str:
    """``ICOHPLIST.lobster``: the exact integrated values."""

    head = (
        "  COHP#    atomMU    atomNU   distance   translation   "
        "ICOHP (at) eF    ICOHP (at) eF \n"
        "                                                          "
        "for spin 1       for spin 2 \n"
    )

    rows = [
        ("1", "Co1", "O3", 1.90, (0, 0, 0), -1.20, -1.30),
        ("2", "Co1", "O4", 1.95, (0, 0, -1), -1.10, -1.15),
        ("3", "Li2", "O3", 2.15, (0, 0, 0), -0.35, -0.37),
    ]

    body = ""

    for index, a, b, length, image, up, down in rows:

        body += (
            f"   {index:>6}   {a:>8}  {b:>8}   {length:8.5f}  "
            f"{image[0]:>4}{image[1]:>4}{image[2]:>4}   "
            f"{up:14.5f}"
            + (f"   {down:14.5f}" if spin_polarized else "")
            + " \n"
        )

    return head + body


#: What each interaction integrates to at the Fermi level, summed over
#: spin channels -- the same numbers :func:`icohplist` writes, so the
#: curve file and the list file describe one run and can be checked
#: against each other.
TOTALS = (-2.50, -2.25, -0.72)


def cohpcar(spins: int = 2, lengths=(1.90, 1.95, 2.15)) -> str:
    """
    ``COHPCAR.lobster``: the curves, on a five point energy grid.

    The shape is invented but the two things that matter are real: it is
    negative below the Fermi level, which is COHP's convention for
    bonding, and each curve's running integral reaches that bond's
    entry in :data:`TOTALS` exactly at the Fermi level.
    """

    energies = np.linspace(-4.0, 4.0, 5)

    entries = 1 + len(lengths)

    head = (
        "ESCALE ; pCOHP file generated by LOBSTER. Energy is shifted "
        "such that the Fermi level lies at 0 eV.\n"
        f"   {entries:>8} {spins:>10} {len(energies):>10} "
        f" -4.00000e+00   4.00000e+00   3.00000e+00 \n"
        "Average\n"
    )

    names = [("Co1", "O3"), ("Co1", "O4"), ("Li2", "O3")]

    for number, ((a, b), length) in enumerate(zip(names, lengths), start=1):
        head += f"No.{number}:{a}->{b}({length})\n"

    # A bump below the Fermi level, so the integral is negative there and
    # flat above it. Energies are [-4, -2, 0, 2, 4], so the Fermi level
    # is the middle point.
    shape = np.array([-0.5, -1.0, -0.4, 0.2, 0.1])
    running = np.cumsum(shape) * 0.5

    fermi = len(energies) // 2

    # Scaled so each bond's integral passes through its total at E_F, and
    # split evenly between the spin channels.
    scales = [1.0] + [
        total / running[fermi] / spins for total in TOTALS[: len(lengths)]
    ]

    body = ""

    for index, energy in enumerate(energies):

        values = [f"{energy:.5f}"]

        for _ in range(spins):
            for entry in range(entries):

                values.append(f"{shape[index] * scales[entry]:.6f}")
                values.append(f"{running[index] * scales[entry]:.6f}")

        body += " " + " ".join(values) + " \n"

    return head + body


POSCAR = """LiCoO2
1.0
5.000000 0.000000 0.000000
0.000000 5.000000 0.000000
0.000000 0.000000 5.000000
Co Li O
1 1 2
direct
0.000000 0.000000 0.000000
0.500000 0.500000 0.500000
0.380000 0.000000 0.000000
0.000000 0.390000 0.000000
"""


def write(folder, table=None, curves=None, structure=True, quantity="COHP"):
    """Lay out a folder the way LOBSTER leaves one."""

    kind = ch.KINDS[quantity]

    if table is not None:
        (folder / kind.table).write_text(table, encoding="utf-8")

    if curves is not None:
        (folder / kind.curves).write_text(curves, encoding="utf-8")

    if structure:
        (folder / "POSCAR.lobster.vasp").write_text(POSCAR, encoding="utf-8")

    return folder


