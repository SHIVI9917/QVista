def test_the_interaction_list_is_read(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist()))

    assert len(result.bonds) == 3
    assert result.spin_polarized

    first = result.bonds[0]

    assert first.a_label == "Co1"
    assert first.b_label == "O3"
    assert first.length == pytest.approx(1.90)
    assert first.translation == (0, 0, 0)
    assert first.values == [-1.20, -1.30]


def test_a_negative_image_is_read_as_negative(tmp_path):
    """A bond across a face, which is most of them in a dense solid."""

    result = ch.read(write(tmp_path, table=icohplist()))

    assert result.bonds[1].translation == (0, 0, -1)


def test_a_run_without_spin_has_one_column(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist(spin_polarized=False)))

    assert not result.spin_polarized
    assert result.bonds[0].values == [-1.20]
    assert result.bonds[0].raw == pytest.approx(-1.20)


def test_the_spin_channels_are_added_up(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist()))

    assert result.bonds[0].raw == pytest.approx(-2.50)


def test_strength_is_positive_for_a_bond(tmp_path):
    """The sign flip, where it matters: in the number people quote."""

    result = ch.read(write(tmp_path, table=icohplist()))

    assert result.bonds[0].raw < 0
    assert result.bonds[0].strength == pytest.approx(2.50)


def test_coop_keeps_its_own_sign(tmp_path):

    write(tmp_path, table=icohplist(), quantity="COOP")

    result = ch.read(tmp_path, "COOP")

    assert result.bonds[0].raw == pytest.approx(-2.50)
    assert result.bonds[0].strength == pytest.approx(-2.50)


def test_elements_come_off_the_labels(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist()))

    assert result.bonds[0].a_element == "Co"
    assert result.bonds[0].b_element == "O"
    assert result.bonds[2].a_element == "Li"


def test_a_pair_is_named_the_same_way_round_either_way():

    kind = ch.KINDS["COHP"]

    forward = ch.Bond("1", "Co1", "O3", 1.9, (0, 0, 0), [-1.0], kind)
    backward = ch.Bond("2", "O3", "Co1", 1.9, (0, 0, 0), [-1.0], kind)

    assert forward.pair == backward.pair == "Co-O"


def test_a_table_with_no_rows_is_refused(tmp_path):

    write(tmp_path, table="  COHP#  atomMU  atomNU  distance\n")

    with pytest.raises(ch.CohpError, match="No interactions"):
        ch.read(tmp_path)


