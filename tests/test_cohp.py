def test_selection_orders_by_strength(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist()))

    chosen = ch.select(result.bonds)

    assert [bond.a_label for bond in chosen] == ["Co1", "Co1", "Li2"]
    assert chosen[0].strength >= chosen[1].strength >= chosen[2].strength


def test_selection_filters_on_length(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist()))

    assert len(ch.select(result.bonds, max_length=2.0)) == 2
    assert ch.select(result.bonds, max_length=1.0) == []


def test_selection_filters_on_strength(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist()))

    assert len(ch.select(result.bonds, min_strength=1.0)) == 2


def test_selection_filters_on_pair(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist()))

    chosen = ch.select(result.bonds, pairs=["Li-O"])

    assert len(chosen) == 1
    assert chosen[0].a_label == "Li2"


def test_bond_types_are_summarised(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist()))

    rows = ch.by_pair(result.bonds)

    assert [row.pair for row in rows] == ["Co-O", "Li-O"]

    strong = rows[0]

    assert strong.count == 2
    assert strong.strength_mean == pytest.approx((2.50 + 2.25) / 2)
    assert strong.strength_total == pytest.approx(4.75)
    assert strong.length_min == pytest.approx(1.90)
    assert strong.length_max == pytest.approx(1.95)


def test_atoms_are_summarised_from_both_ends(tmp_path):
    """
    An atom takes part in a bond whichever end of the row it is on.

    Counting only the first column would give every second atom no bonds
    at all.
    """

    result = ch.read(write(tmp_path, table=icohplist()))

    rows = {row.label: row for row in ch.by_atom(result.bonds)}

    assert set(rows) == {"Co1", "O3", "O4", "Li2"}

    # Co1 is in two bonds, both as the first atom.
    assert rows["Co1"].count == 2
    assert rows["Co1"].strength_total == pytest.approx(4.75)

    # O3 is in two bonds, both as the second atom.
    assert rows["O3"].count == 2
    assert rows["O3"].strength_total == pytest.approx(2.50 + 0.72)


def test_atom_rows_come_back_strongest_first(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist()))

    totals = [row.strength_total for row in ch.by_atom(result.bonds)]

    assert totals == sorted(totals, reverse=True)


def test_curves_add_up(tmp_path):
    """The COHP of a coordination shell is the sum over its bonds."""

    result = ch.read(write(tmp_path, table=icohplist(), curves=cohpcar()))

    pack = ch.summed_curve(result.bonds[:2])

    assert pack is not None

    energies, (curve, integrated) = pack

    assert energies.shape == (5,)
    assert np.allclose(
        curve,
        result.bonds[0].signed_curve + result.bonds[1].signed_curve,
    )
    assert np.allclose(
        integrated,
        result.bonds[0].signed_integrated + result.bonds[1].signed_integrated,
    )


def test_summing_nothing_gives_nothing(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist()))

    assert ch.summed_curve(result.bonds) is None
    assert ch.summed_curve([]) is None


def test_the_pairs_present_are_listed(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist()))

    assert result.pairs() == ["Co-O", "Li-O"]
    assert set(result.elements()) == {"Co", "O", "Li"}


