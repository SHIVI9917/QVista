def test_only_cohp_flips_its_sign():
    """
    The one convention that catches people out.

    COHP is negative for a bond and COOP and COBI are positive, so only
    COHP is negated to make a bonding interaction read positive.
    """

    assert ch.KINDS["COHP"].flip
    assert not ch.KINDS["COOP"].flip
    assert not ch.KINDS["COBI"].flip


def test_each_quantity_names_its_own_axes():

    assert ch.KINDS["COHP"].strength_label == "-ICOHP"
    assert ch.KINDS["COHP"].curve_label == "-COHP"
    assert ch.KINDS["COOP"].strength_label == "ICOOP"
    assert ch.KINDS["COBI"].curve_label == "COBI"


def test_the_quantities_a_folder_has_are_reported(tmp_path):

    write(tmp_path, table=icohplist(), curves=cohpcar())

    assert ch.available(tmp_path) == ["COHP"]

    (tmp_path / ch.KINDS["COBI"].table).write_text(icohplist())

    assert ch.available(tmp_path) == ["COHP", "COBI"]


