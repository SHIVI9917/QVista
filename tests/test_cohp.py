def test_curves_are_attached_to_their_bonds(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist(), curves=cohpcar()))

    assert result.has_curves
    assert result.energies.shape == (5,)
    assert result.efermi == pytest.approx(3.0)

    for bond in result.bonds:
        assert bond.curve is not None
        assert bond.curve.shape == (5,)
        assert bond.integrated is not None


def test_the_curve_is_negated_only_for_cohp(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist(), curves=cohpcar()))

    bond = result.bonds[0]

    assert np.allclose(bond.signed_curve, -bond.curve)

    write(tmp_path, table=icohplist(), curves=cohpcar(), quantity="COOP")

    coop = ch.read(tmp_path, "COOP")

    assert np.allclose(coop.bonds[0].signed_curve, coop.bonds[0].curve)


def test_bonding_below_the_fermi_level_is_positive_after_the_flip(tmp_path):
    """
    What the sign convention is for.

    The fixture is bonding below E_F, which means a negative COHP; drawn
    as -COHP it has to come out positive, or the plot says antibonding.
    """

    result = ch.read(write(tmp_path, table=icohplist(), curves=cohpcar()))

    curve = result.bonds[0].signed_curve
    below = result.energies < 0

    assert (curve[below] > 0).all()


def test_site_numbers_come_from_the_curve_file(tmp_path):
    """Without them the bonds cannot be placed on the structure."""

    result = ch.read(write(tmp_path, table=icohplist(), curves=cohpcar()))

    assert result.bonds[0].a_site == 0
    assert result.bonds[0].b_site == 2


def test_files_from_different_runs_are_refused(tmp_path):
    """
    A length disagreement means the two files are not the same run.

    Carrying on would attach one run's curves to another run's numbers,
    which is worse than refusing: everything downstream would look fine.
    """

    write(tmp_path, table=icohplist(), curves=cohpcar(lengths=(1.90, 2.60, 2.15)))

    with pytest.raises(ch.CohpError, match="different runs"):
        ch.read(tmp_path)


def test_without_curves_the_table_still_loads(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist()))

    assert len(result.bonds) == 3
    assert not result.has_curves
    assert result.bonds[0].signed_curve is None
    assert any("nothing to plot" in note for note in result.notes)


def test_the_cell_average_is_kept(tmp_path):

    result = ch.read(write(tmp_path, table=icohplist(), curves=cohpcar()))

    assert result.average is not None
    assert result.signed_average is not None
    assert np.allclose(result.signed_average, -result.average)


def test_the_integral_at_the_fermi_level_is_the_strength(tmp_path):
    """
    The invariant tying the two files together.

    The number in the list file is the exact integral of the curve up to
    the Fermi level, so reading it off the curve has to give the same
    answer. It is what says the sign flip, the spin summation and the
    energy grid are all being handled consistently -- get any one of them
    wrong and these two numbers part company.
    """

    result = ch.read(write(tmp_path, table=icohplist(), curves=cohpcar()))

    for bond in result.bonds:

        assert ch.strength_at_fermi(bond) == pytest.approx(
            bond.strength, abs=1e-4
        )


